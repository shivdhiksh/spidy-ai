"""
ToolExecutor — Mark XXXIX OR Structured Tool Execution Engine
=============================================================
Coordinates the structured tool execution pipeline:
Model Request → Tool Parsing → Schema Validation → Permission Gate →
Skill Execution → Real Action Verification → Tool Result → Model → Final Response

Guarantees:
1. Hard separation between NORMAL_TEXT_RESPONSE and TOOL_CALL.
2. Tool-shaped JSON is NEVER returned directly to the user or TTS.
3. Every tool execution is verified against the real operating system / filesystem.
4. The LLM receives the real tool execution result to formulate its final response.
"""

from __future__ import annotations

import json
import re
from typing import TYPE_CHECKING, Any

from spidy.logging.logger import get_logger
from spidy.skills.base import SkillContext, SkillResult
from spidy.skills.tool_registry import GLOBAL_TOOL_REGISTRY, ToolDefinition

if TYPE_CHECKING:
    from spidy.core.event_bus import EventBus
    from spidy.llm.client import BaseLLMClient, LLMMessage, LLMResponse
    from spidy.permissions.manager import PermissionManager
    from spidy.skills.registry import SkillRegistry

log = get_logger(__name__)

# Patterns that indicate a tool call embedded in model output
_JSON_BLOCK_RE = re.compile(r"```(?:json)?\s*(\{[\s\S]*?\})\s*```", re.DOTALL)
_RAW_JSON_RE = re.compile(r"(\{[\s\S]*\})", re.DOTALL)


class ToolExecutor:
    """
    Executes tool calls generated by LLMs or structured agent plans.
    """

    def __init__(
        self,
        skill_registry: "SkillRegistry",
        permission_manager: "PermissionManager | None" = None,
        bus: "EventBus | None" = None,
    ) -> None:
        self._registry = skill_registry
        self._permissions = permission_manager
        self._bus = bus
        self._tools = GLOBAL_TOOL_REGISTRY

    # ── Tool Call Extraction & Parsing ────────────────────────────────────────

    @classmethod
    def parse_tool_call(cls, text: str) -> tuple[str, dict[str, Any]] | None:
        """
        Extract a tool call from LLM response text if present.
        Recognizes formats:
          1. {"tool": "file.search", "args": {"query": "resume"}}
          2. {"action": "search_files", "query": "resume"}
          3. {"name": "file.search", "parameters": {"query": "resume"}}
          4. ```json { ... } ```
        Returns (tool_name, parameters_dict) or None.
        """
        if not text or not text.strip():
            return None

        clean = text.strip()

        # Check for fenced code block first
        block_match = _JSON_BLOCK_RE.search(clean)
        candidate_json = block_match.group(1) if block_match else None

        if not candidate_json:
            # Check if whole string or trimmed string is JSON
            if clean.startswith("{") and clean.endswith("}"):
                candidate_json = clean
            else:
                raw_match = _RAW_JSON_RE.search(clean)
                if raw_match:
                    candidate_json = raw_match.group(1)

        if not candidate_json:
            return None

        try:
            data = json.loads(candidate_json)
            if not isinstance(data, dict):
                return None

            tool_name = (
                data.get("tool")
                or data.get("tool_name")
                or data.get("name")
                or data.get("action")
                or data.get("skill_action")
            )
            if not tool_name or not isinstance(tool_name, str):
                return None

            # Extract arguments
            args = (
                data.get("args")
                or data.get("parameters")
                or data.get("params")
                or data.get("arguments")
            )
            if args is None:
                # Top-level dict keys other than control keys are args
                args = {k: v for k, v in data.items() if k not in ("tool", "tool_name", "name", "action", "skill_action", "skill", "type")}

            if not isinstance(args, dict):
                args = {}

            # Verify it matches a known tool or skill
            if GLOBAL_TOOL_REGISTRY.is_known_tool(tool_name) or tool_name.replace(".", "_") in ("file_search", "search_files", "open_file", "create_file", "launch_app"):
                return str(tool_name), args

        except (json.JSONDecodeError, ValueError):
            return None

        return None

    # ── Tool Execution ────────────────────────────────────────────────────────

    async def execute_tool(
        self,
        tool_name: str,
        args: dict[str, Any],
        session_id: str = "",
        user_name: str = "User",
    ) -> SkillResult:
        """
        Execute a tool by name with arguments through the permission and verification pipeline.
        """
        tool_def = self._tools.get_tool(tool_name)
        if tool_def is None:
            msg = f"Unknown tool '{tool_name}'. Tool is not registered in SPIDY."
            log.warning("ToolExecutor: {msg}", msg=msg)
            return SkillResult(success=False, message=msg, action_taken=tool_name)

        # 1. Parameter validation & coercion
        coerced_args, errors = self._tools.validate_parameters(tool_def, args)
        if errors:
            err_msg = f"Parameter validation failed for tool '{tool_def.name}': " + "; ".join(errors)
            log.warning("ToolExecutor: {err}", err=err_msg)
            return SkillResult(success=False, message=err_msg, action_taken=tool_def.name)

        # 2. Permission Check
        if self._permissions is not None:
            allowed = await self._permissions.check(
                tool_def.skill_action,
                tier=tool_def.permission_tier,
                session_id=session_id,
            )
            if not allowed:
                msg = f"Permission denied for '{tool_def.name}' (tier {tool_def.permission_tier})."
                log.warning("ToolExecutor: {msg}", msg=msg)
                return SkillResult(success=False, message=msg, action_taken=tool_def.name)

        # 3. Find underlying skill
        skill = self._registry.find_skill_for_action(tool_def.skill_action)
        if skill is None:
            msg = f"No handler registered for skill action '{tool_def.skill_action}' (tool '{tool_def.name}')."
            log.error("ToolExecutor: {msg}", msg=msg)
            return SkillResult(success=False, message=msg, action_taken=tool_def.name)

        # 4. Execute Skill Context
        ctx = SkillContext(
            action=tool_def.skill_action,
            params=coerced_args,
            session_id=session_id,
            user_name=user_name,
        )

        log.info(
            "[TOOL_EXECUTE] tool={tool} action={action} args={args}",
            tool=tool_def.name,
            action=tool_def.skill_action,
            args=str(coerced_args)[:120],
        )

        try:
            result = await skill.execute(tool_def.skill_action, ctx)
            log.info(
                "[TOOL_RESULT] tool={tool} success={ok} message='{msg}'",
                tool=tool_def.name,
                ok=result.success,
                msg=result.message[:120] if result.message else "",
            )
            return result
        except Exception as exc:  # noqa: BLE001
            log.error("ToolExecutor: execution failed for '{tool}': {exc}", tool=tool_def.name, exc=exc)
            return SkillResult.fail(f"Tool '{tool_def.name}' raised an error: {exc}", error=exc, action_taken=tool_def.name)

    # ── Full Model-Tool Loop (Mark XXXIX OR Standard) ─────────────────────────

    async def run_tool_loop(
        self,
        llm: "BaseLLMClient",
        messages: list["LLMMessage"],
        session_id: str = "",
        user_name: str = "User",
        max_tool_turns: int = 5,
    ) -> tuple[str, list[dict[str, Any]]]:
        """
        Execute iterative tool loop with the LLM.
        Returns (final_natural_language_response, executed_tools_list).
        """
        from spidy.llm.client import LLMMessage

        executed_tools: list[dict[str, Any]] = []
        current_messages = list(messages)

        for turn_idx in range(max_tool_turns):
            response = await llm.complete(current_messages)
            if not response.success:
                log.warning("ToolExecutor: LLM completion failed: {err}", err=response.error_message)
                return response.text or "I encountered an error processing that request.", executed_tools

            response_text = response.text.strip()

            # Parse tool call
            tool_call = self.parse_tool_call(response_text)
            if tool_call is None:
                # Pure natural language response — finished!
                return response_text, executed_tools

            tool_name, tool_args = tool_call
            log.info(
                "[TOOL_CALL] tool={tool} args={args} turn={t}",
                tool=tool_name,
                args=str(tool_args)[:100],
                t=turn_idx + 1,
            )

            # Execute real action
            result = await self.execute_tool(tool_name, tool_args, session_id=session_id, user_name=user_name)
            executed_tools.append({
                "tool": tool_name,
                "args": tool_args,
                "success": result.success,
                "result": result.data or result.message,
            })

            # Append assistant message (the tool call) and user/tool observation message
            current_messages.append(LLMMessage(role="assistant", content=response_text))

            observation_content = (
                f"[TOOL_RESULT for {tool_name}]\n"
                f"Success: {result.success}\n"
                f"Message: {result.message}\n"
            )
            if result.data:
                try:
                    observation_content += f"Data: {json.dumps(result.data, default=str)}\n"
                except Exception:  # noqa: BLE001
                    observation_content += f"Data: {result.data}\n"
            observation_content += "Use this real verified tool result to answer the user naturally. Do not output raw JSON."

            current_messages.append(LLMMessage(role="user", content=observation_content))

        # If max tool turns exceeded, do one final text-only completion
        final_resp = await llm.complete(current_messages)
        final_text = final_resp.text.strip()
        # Clean any trailing JSON if present
        clean_text = _JSON_BLOCK_RE.sub("", final_text).strip()
        return clean_text or final_text, executed_tools
